Advanced Flutter Task – Product Search & Filter App
Task:
Build a Flutter mini e-commerce app that displays a list of products and allows users to search, filter, sort, and view product details.
Requirements:
1.	Create a product list using local/mock JSON data.
2.	Display products using ListView or GridView.
3.	Add a search bar to search products by name.
4.	Add category and price filters.
5.	Add sorting:
o	Price: Low → High
o	Price: High → Low
6.	Create a Product Details screen when a product is tapped.
7.	Implement proper loading, empty, and error states.
8.	Use a state management solution such as Provider, Riverpod, or BLoC.
9.	Keep the UI clean, responsive, and well-structured.
Objective:
This task should test the student's understanding of Flutter UI, state management, navigation, filtering, searching, local data handling, and clean architecture within a 1-hour timeframe.
